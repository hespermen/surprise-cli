import assert from "node:assert/strict";
import { test } from "node:test";

import { stripControl } from "./safeText.ts";
import { truncate } from "./format.ts";
import { fit } from "../tui/theme.ts";

/**
 * Главная проверка файла.
 *
 * Терминал — интерпретатор, а не экран. Каждая из этих строк, попав на него
 * без чистки, делает не то, что выглядит: пишет в буфер обмена, стирает экран
 * под поддельный запрос пароля или заставляет терминал ответить во входной
 * поток, который плеер читает в raw-режиме.
 */
test("управляющие последовательности вырезаются", () => {
  const cases: Array<[string, string]> = [
    ["SURPRISE\u001b]52;c;ZXZpbA==\u0007", "SURPRISE]52;c;ZXZpbA=="],
    ["до\u001b[2J\u001b[Hпосле", "до[2J[Hпосле"],
    ["запрос\u001b[21t", "запрос[21t"],
    ["строка\u0000с нулём", "строкас нулём"],
    ["возврат\u0008каретки", "возвраткаретки"],
  ];
  for (const [raw, expected] of cases) {
    assert.equal(stripControl(raw), expected, `не очистилось: ${JSON.stringify(raw)}`);
  }
});

/**
 * Однобайтовый CSI — тот же управляющий код без ESC впереди.
 *
 * Фильтр, знающий только про \u001b, пропускает его целиком, и защита
 * оказывается декоративной.
 */
test("диапазон C1 вырезается тоже", () => {
  assert.equal(stripControl("до\u009b2Jпосле"), "до2Jпосле");
  assert.equal(stripControl("x\u009dy"), "xy");
});

/** Перенос строки в однострочном поле ломает раскладку не хуже ESC. */
test("переводы строк вырезаются", () => {
  assert.equal(stripControl("одна\nдве\r\nтри"), "однадветри");
});

/** Табуляция встречается в осмысленном тексте — её оставляем. */
test("обычный текст не страдает", () => {
  for (const text of ["SURPRISE.FM w/ Ballu", "Ballu — диджей", "колонка\tзначение", "emoji 🎧", ""]) {
    assert.equal(stripControl(text), text, `испортился обычный текст: ${JSON.stringify(text)}`);
  }
});

/**
 * Чистка стоит ВНУТРИ обрезки, а не рядом с ней.
 *
 * Через truncate и fit проходит почти всё, что сервер показывает человеку.
 * Требовать от каждого из полутора десятков вызовов помнить про отдельный
 * вызов очистки — значит однажды забыть.
 */
test("обрезка чистит сама", () => {
  assert.equal(truncate("имя\u001b]52;c;x\u0007", 100), "имя]52;c;x");
  assert.equal(fit("имя\u001b[2J", 100), "имя[2J");
});

/** Ширина считается ПОСЛЕ чистки: иначе невидимые символы съедали бы колонки. */
test("вырезанное не занимает ширину", () => {
  const dirty = "\u001b[2J\u001b[2J\u001b[2Jабв";
  assert.equal(fit(dirty, 6), "[2J[2…", "ширина должна считаться по видимому");
  assert.equal([...truncate("\u0000\u0000абвгд", 5)].length, 5);
});

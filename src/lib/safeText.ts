/**
 * Очистка текста, пришедшего с сервера, перед выводом в терминал.
 *
 * Терминал — не экран, а ИНТЕРПРЕТАТОР. Строка «\u001b]52;c;…\u0007» не
 * печатается, а записывает произвольные данные в буфер обмена; «\u001b[2J»
 * стирает экран, после чего можно нарисовать поддельный запрос пароля; на
 * запросы вроде «\u001b[21t» терминал отвечает САМ, и ответ приходит во
 * входной поток — а stdin у плеера в это время в raw-режиме.
 *
 * Названия выпусков, описания артистов и тексты ошибок приходят с сервера и
 * идут прямо на экран. Пока сервер свой, ничего этого там нет; но защита от
 * подменённого ответа стоит один вызов replace, а её отсутствие превращает
 * любое поле в базе в управление чужим терминалом.
 *
 * Примечательно, что ввод С КЛАВИАТУРЫ от этого уже защищён (см. splitBurst в
 * tui/App.tsx) — а данные сервера, которым доверия должно быть меньше, шли
 * насквозь.
 */

/**
 * Что вырезаем.
 *
 * Весь диапазон C0 (кроме табуляции — она встречается в осмысленном тексте),
 * DEL и диапазон C1: последний важен отдельно, потому что «\u009b» — это
 * однобайтовый CSI, то есть та же управляющая последовательность без ESC
 * впереди. Фильтр, знающий только про «\u001b», её пропускает.
 *
 * Переводы строки тоже уходят: поля, которые мы выводим, однострочные, и
 * перенос в названии выпуска ломает раскладку не хуже управляющего символа.
 */
const CONTROL = /[\u0000-\u0008\u000A-\u001F\u007F-\u009F]/g;

/** Строка, которую можно напечатать, ничего не сломав. */
export function stripControl(text: string): string {
  return text.replace(CONTROL, "");
}

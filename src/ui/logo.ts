/**
 * Логотип станции блочными символами.
 *
 * Рисуется блоками, а не картинкой: терминал картинок не показывает, а из тех,
 * что показывают, каждый делает это по-своему (kitty, iTerm2, sixel — три
 * несовместимых протокола). Блоки работают везде одинаково.
 *
 * Модуль СПЕЦИАЛЬНО без ink: логотип нужен и полноэкранному интерфейсу, и
 * простому `surprise radio`, который рисует несколько строк в обычный поток
 * вывода. Собери его внутри компонента — и второму пришлось бы тянуть React
 * ради пяти строк текста либо держать вторую копию того же рисунка.
 */

/**
 * Блочный шрифт, пять строк высотой.
 *
 * Только те символы, что есть в названии станции: полный алфавит здесь был бы
 * мёртвым кодом, а его никто не проверяет.
 */
const GLYPHS: Record<string, readonly string[]> = {
  S: ["███", "█  ", "███", "  █", "███"],
  U: ["█ █", "█ █", "█ █", "█ █", "███"],
  R: ["███", "█ █", "███", "█ █", "█ █"],
  P: ["███", "█ █", "███", "█  ", "█  "],
  I: ["███", " █ ", " █ ", " █ ", "███"],
  E: ["███", "█  ", "███", "█  ", "███"],
  F: ["███", "█  ", "███", "█  ", "█  "],
  M: ["█ █", "███", "███", "█ █", "█ █"],
  ".": ["   ", "   ", "   ", "   ", " █ "],
  " ": ["  ", "  ", "  ", "  ", "  "],
};

const WORDMARK = "SURPRISE.FM";
export const LOGO_HEIGHT = 5;

/**
 * Знак станции: залитый квадрат с тёмной буквой внутри.
 *
 * Собирается из пиксельной сетки, а не пишется готовыми символами. Причина в
 * высоте: на логотип отведено пять строк, а букве нужны поля сверху и снизу,
 * иначе она упирается в край квадрата. Половинные блоки дают десять пиксельных
 * рядов в тех же пяти строках — этого хватает и на букву, и на поля.
 *
 * Единица — залитая часть квадрата, ноль — сама буква: она тёмная, как на
 * фирменном знаке.
 */
const MARK_PIXELS = [
  "11111111",
  "10000001",
  "10000001",
  "10111111",
  "10000001",
  "10000001",
  "11111101",
  "10000001",
  "10000001",
  "11111111",
] as const;

/** Пара пиксельных рядов в одну строку символов. */
function packRows(top: string, bottom: string): string {
  let out = "";
  for (let column = 0; column < top.length; column += 1) {
    const upper = top[column] === "1";
    const lower = bottom[column] === "1";
    // Полный блок, верхняя половина, нижняя половина, пусто.
    out += upper && lower ? "█" : upper ? "▀" : lower ? "▄" : " ";
  }
  return out;
}

const MARK: string[] = [];
for (let row = 0; row < MARK_PIXELS.length; row += 2) {
  MARK.push(packRows(MARK_PIXELS[row]!, MARK_PIXELS[row + 1]!));
}

/** Строки логотипа: знак, пробел, слово. */
export const LOGO_ROWS: readonly string[] = Array.from({ length: LOGO_HEIGHT }, (_, line) => {
  const word = [...WORDMARK].map((char) => GLYPHS[char]?.[line] ?? "   ").join(" ");
  return `${MARK[line] ?? ""}  ${word}`;
});

export const LOGO_WIDTH = Math.max(...LOGO_ROWS.map((row) => [...row].length));

/**
 * Логотип для окна такой ширины — или ничего.
 *
 * Не влезает — не показываем: обрезанный логотип читается как сломанный
 * интерфейс, а не как логотип, которому не хватило места.
 */
export function logoRows(width: number): readonly string[] | null {
  return width >= LOGO_WIDTH + 2 ? LOGO_ROWS : null;
}

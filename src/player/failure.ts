/**
 * Перевод ругани плеера в человеческую причину.
 *
 * Общий модуль для обоих бэкендов: ffmpeg и mpv используют одну библиотеку
 * ввода-вывода и жалуются похоже, а лечится это одинаково.
 *
 * Показывать сырой лог целиком бессмысленно — там десяток строк про внутренности
 * ALSA и PipeWire, среди которых одна значимая.
 */

export function describeFailure(stderrTail: string, binary: string): string {
  const text = stderrTail.trim();

  if (/ALSA|snd_|pipewire|pw\.conf|No such (audio )?device|Could not open|audio device|AO: \[/i.test(text)) {
    return (
      `${binary} не смог открыть звуковое устройство — играть некуда. ` +
      "Похоже, в системе нет звуковой карты (частый случай для контейнера и SSH-сессии)."
    );
  }

  // Коды HTTP опознаём по САМОМУ КОДУ, а не по тексту статуса.
  //
  // Ловушка: «Not Found» встречается в сообщениях, к HTTP отношения не имеющих —
  // «moov atom not found», «Stream not found», «codec not found». Совпадение по
  // тексту выдавало на битый файл бодрое «Файл не найден на сервере (404)», и
  // человек шёл проверять ссылку вместо файла. Цифры такой двусмысленности не
  // имеют, а \b не даёт поймать 404 внутри случайного числа.
  if (/\b403\b/.test(text)) return "Сервер отказал в доступе к файлу (403).";
  if (/\b404\b/.test(text)) return "Файл не найден на сервере (404).";
  if (/Invalid data|moov atom|Header missing|not found/i.test(text)) return "Файл повреждён или это не аудио.";

  const lastLine = text.split("\n").map((line) => line.trim()).filter(Boolean).pop();
  return lastLine ? `${binary}: ${lastLine}` : `${binary} завершился сразу, ничего не проиграв.`;
}

/**
 * Сколько ждать первых признаков жизни после загрузки файла.
 *
 * Нужно ровно для одного случая, зато неприятного: mpv без звукового устройства
 * файл ОТКРЫВАЕТ (кодек определяется, дорожка выбирается), но часы не запускает
 * — time-pos остаётся «property unavailable» навсегда. Процесс жив, ошибок нет,
 * а строка состояния вечно висит на `--:--`. Молчать в этом месте нельзя: с
 * точки зрения человека плеер просто не работает и не говорит почему.
 *
 * Значение с запасом на медленную сеть: по SSH из другой страны первые данные
 * приходят не мгновенно.
 */
export const PLAYBACK_WATCHDOG_MS = 8_000;
